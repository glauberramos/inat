#!/usr/bin/env python3
"""Build birds-porto-alegre-ebird.js, the eBird presence chart on each card of birds-porto-alegre.html.

Reads the bar chart that eBird exports for Porto Alegre (BR-RS-328) and keeps, for every bird in
birds-porto-alegre-data.js, the share of checklists that reported it in each of the year's 48 weeks.
eBird names birds in Portuguese there, so birds are matched by name; ALIASES covers the ones eBird
names differently.

To get the file: open https://ebird.org/barchart?r=BR-RS-328&bmo=1&emo=12&byr=1900&eyr=2026 with the
site in Portuguese and download the histogram data (a tab-separated .txt).

Requires: node.
Usage:    python3 scripts/bird-ebird-barchart.py <ebird_BR-RS-328_..._barchart.txt>
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "birds-porto-alegre-data.js"
OUT = ROOT / "birds-porto-alegre-ebird.js"
REGION = "BR-RS-328"
WEEKS = 48

# Our name -> eBird's, where they differ. eBird has no row for domestic birds (Galinha-doméstica).
ALIASES = {
    "Bacurau-da-telha": "bacurau-da-telha/de-roraima",
    "Gavião-carrapateiro": "carrapateiro",
    "Vira-folha": "vira-folha/vira-folha-cearense",
    "Pernilongo-de-costas-brancas": "pernilongo-de-costas-negras/de-costas-brancas",
    "Tesourinha": "tesourinha/tesourinha-do-norte",
}


def load_birds():
    # The data file is a plain script; let node evaluate it and hand us JSON. It goes in on stdin,
    # as it's too long for a command-line argument.
    code = f"{DATA.read_text()}\nprocess.stdout.write(JSON.stringify(BIRDS_PORTO_ALEGRE));"
    return json.loads(subprocess.run(["node"], input=code, capture_output=True, check=True, text=True).stdout)


def read_barchart(path):
    """Each name's weekly frequencies (0-1)."""
    samples, rows = None, {}
    for line in pathlib.Path(path).read_text(encoding="utf-8").splitlines():
        cells = line.rstrip("\t").split("\t")
        if len(cells) != WEEKS + 1 or not cells[0].strip():
            continue
        name, values = cells[0].strip(), [float(v) for v in cells[1:]]
        if name.startswith("Sample Size"):
            samples = values
        else:
            rows[name.lower()] = values
    if samples is None or not rows:
        sys.exit(f"{path} doesn't look like an eBird bar chart export")
    return rows


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rows = read_barchart(sys.argv[1])
    weeks, missing = {}, []
    for bird in load_birds():
        values = rows.get(ALIASES.get(bird["name"], bird["name"]).lower())
        if values is None:
            missing.append(bird["name"])
            continue
        # Tenths of a percent; anything reported at all stays above zero so it still shows
        weeks[bird["inatTaxonId"]] = [max(1, round(v * 1000)) if v > 0 else 0 for v in values]

    lines = [
        "// Generated by scripts/bird-ebird-barchart.py from eBird's bar chart for Porto Alegre, all years:",
        f"// https://ebird.org/barchart?r={REGION}&bmo=1&emo=12&byr=1900&eyr=2026",
        "// For each bird (by iNaturalist taxon id), the share of eBird checklists that reported it in each",
        "// of the year's 48 weeks (four per month), in tenths of a percent. Don't edit by hand.",
        f'const BIRD_EBIRD_REGION = "{REGION}";',
        "// prettier-ignore",
        "const BIRD_EBIRD_WEEKS = {",
        *(f"  {taxon}: [{', '.join(map(str, values))}]," for taxon, values in weeks.items()),
        "};",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{len(weeks)} birds written to {OUT.name}; not in eBird's chart: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main()
